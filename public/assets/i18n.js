export function chooseLanguage(search = '', saved = null, browser = 'en') {
  const override = new URLSearchParams(search).get('lang')?.toLowerCase();
  if (override === 'en' || override === 'zh') return override;
  if (saved === 'en' || saved === 'zh') return saved;
  return browser.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
export function translate(lang, key, vars = {}) {
  const value = messages[lang]?.[key] ?? messages.en[key];
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
